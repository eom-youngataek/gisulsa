def classify_question_domain(text):
    t = text.lower()
    best = None
    best_score = 0
    for dom, keys in QUESTION_DOMAIN_KEYWORDS.items():
        score = sum(1 for k in keys if k in t)
        if score > best_score:
            best_score = score
            best = dom
    return best  # None if no match
